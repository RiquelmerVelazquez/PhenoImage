library(phenoImage)
stopifnot(as.character(packageVersion("phenoImage")) == "4.8.0")
app <- system.file("app", package="phenoImage")
stopifnot(file.exists(file.path(app,"app.R")))
e <- new.env(parent=globalenv())
sys.source(file.path(app,"R","distribucion.R"),e)
e$cipat_verificar_archivos(app)
sys.source(file.path(app,"R","segmentacion_muestras.R"),e)
sys.source(file.path(app,"R","exploracion.R"),e)
d <- data.frame(R=c(100,101,40,41,175,176),G=c(80,81,150,151,160,161),B=c(60,61,45,46,120,121),clase=rep(0:2,each=2),zona=1:6)
m <- e$entrenar_muestras_cipat(d,TRUE)
stopifnot(identical(e$predecir_muestras_cipat(as.matrix(d[1:3]),m),as.numeric(d$clase)))
b <- d[d$clase != 2,]
m2 <- e$entrenar_muestras_cipat(b,FALSE)
stopifnot(!any(m2$clases==2),all(e$predecir_muestras_cipat(as.matrix(b[1:3]),m2)==b$clase))
cov <- e$resumir_clases_cobertura_cipat(c(0,1,2,NA),c(.5,1,1,1),TRUE,2,8)
stopifnot(isTRUE(all.equal(as.numeric(cov[1:4]),c(40,40,20,80))))
cov2 <- e$resumir_clases_cobertura_cipat(c(0,1,NA),c(1,1,1),FALSE,1,3)
stopifnot(is.na(cov2$Plant_ground_cover_image_Dry_pct),cov2$Plant_ground_cover_image_Total_pct==cov2$Plant_ground_cover_image_Green_pct)
v <- data.frame(id="101",NDVI_mean=.7,NDVI_sum=2,Canopy_height_image_mean=45,Canopy_height_image_p90=60,Canopy_height_image_p75=50,Plant_ground_cover_image_Green_pct=80,Plant_ground_cover_image_Dry_pct=NA_real_)
bs <- unname(e$variables_basicas_eda(v))
stopifnot(all(c("Canopy_height_image_mean","Canopy_height_image_p90") %in% bs),!any(c("NDVI_sum","Canopy_height_image_p75","Plant_ground_cover_image_Dry_pct") %in% bs))
stopifnot(length(e$variables_visibles_eda(v,"avanzada"))==ncol(v)-1L)
stopifnot(identical(unname(e$variables_visibles_eda(v,"personalizada","NDVI_sum")),"NDVI_sum"))
cat("PhenoImage 4.8.0: installation and smoke checks passed.\n")
