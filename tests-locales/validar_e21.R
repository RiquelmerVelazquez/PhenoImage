library(phenoImage)
stopifnot(as.character(packageVersion('phenoImage'))=='4.7.0.21',!requireNamespace('cipat',quietly=TRUE))
app <- phenoImage:::.app_path()
phenoImage:::.app_distribution(app)
cat('PASS: paquete independiente instalado, sin CIPAT y sin datos de ejemplo obligatorios.\n')
local({
 root <- tempfile('pheno-e21-');dir.create(root)
 old <- getOption('phenoImage.examples_dir');options(phenoImage.examples_dir=file.path(root,'datos'))
 on.exit({options(phenoImage.examples_dir=old);unlink(root,recursive=TRUE)},add=TRUE)
 stopifnot(!any(example_status()$Instalado))
 missing <- tryCatch({example_path('rgb');NULL},error=conditionMessage)
 stopifnot(grepl('opcional',missing,fixed=TRUE))
 for(module in c('rgb','sentera')) {
   source <- file.path(root,'source');dir.create(file.path(source,module),recursive=TRUE,showWarnings=FALSE)
   required <- phenoImage:::.example_files(module)
   for(f in required)writeLines(paste(module,f),file.path(source,module,f))
   archive <- file.path(root,paste0(module,'.zip'))
   zip::zipr(archive,files=paste0(module,'/',required),root=source,include_directories=FALSE,mode='mirror')
   stopifnot(setequal(utils::unzip(archive,list=TRUE)$Name,paste0(module,'/',required)))
   install_examples(archive)
   stopifnot(all(file.exists(file.path(example_path(module),required))))
   for(f in required)stopifnot(identical(readLines(file.path(source,module,f)),readLines(file.path(example_path(module),f))))
   error <- tryCatch({install_examples(archive);NULL},error=conditionMessage)
   stopifnot(grepl('ya existe',error,fixed=TRUE))
   install_examples(archive,overwrite=TRUE)
 }
 stopifnot(all(example_status()$Instalado))
 cat('PASS: instalación RGB/Sentera, archivos y shapefiles conservados, rechazo de sobrescritura implícita y reemplazo explícito.\n')
 # Integración con el selector existente de la aplicación.
 e <- new.env(parent=globalenv());sys.source(file.path(app,'R/indices_editables.R'),e);sys.source(file.path(app,'R/ejemplos.R'),e)
 for(module in c('sentera','phantom')) {
   config <- e$configuracion_ejemplo_cipat(module,raiz=app)
   stopifnot(file.exists(config$parcelas))
 }
 cat('PASS: ambos módulos encuentran ejemplos externos a la biblioteca del paquete.\n')
 # ZIP ajeno e incompleto: debe fallar sin alterar los datos instalados.
 bad <- file.path(root,'invalido.zip');writeLines('no',file.path(root,'otro.txt'))
 zip::zipr(bad,files='otro.txt',root=root)
 error <- tryCatch({install_examples(bad,overwrite=TRUE);NULL},error=conditionMessage)
 stopifnot(!is.null(error),all(example_status()$Instalado))
 cat('PASS: ZIP incompleto/ajeno rechazado sin modificar los ejemplos instalados.\n')
})
for(p in c(file.path(app,'app.R'),list.files(file.path(app,'R'),pattern='\\.R$',full.names=TRUE)))parse(p)
cat('PASS: sintaxis del aplicativo y todos sus módulos.\n')
status <- check_installation();stopifnot(all(c('shiny','pliman','glcm')%in%status$Paquete))
cat('PASS: dependencias y versiones comprobables sin ejemplos ni CIPAT.\n')
